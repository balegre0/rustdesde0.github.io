fn main() {
    // 1. \n salta de línea; \t es un tabulador.
    println!("uno\ndos");
    println!("a\tb\tc");
    // 2. \" pone comillas dentro del texto; \\ es una barra invertida.
    println!("Dijo \"hola\" y se fue");
    println!("C:\\dev\\hola");
    // 3. print! no salta de línea al final.
    print!("sin ");
    print!("salto");
    println!();
}
